"""The weekly review report (reports/YYYY-MM-DD-weekly.md).

Written by deterministic templates from the files in data/; no language model
writes any part of it. Each item that differs from the program's own figures
is phrased "The dashboard states X. Public records show Y." (or, where both
figures are the program's own, names both sources), with links and as-of
dates, and marked as needing human review. The wording guard checks every
line except verbatim quotations of the program (lines starting with ">").
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .later_receipts import _checks, day_manifests, final_raw_result, run_items
from .store import Archive
from .wording import check_text

REPORT_HEADING = "## Needs human review"


def _rows(root: Path, name: str) -> list[dict]:
    return json.loads((Path(root) / "data" / f"{name}.json").read_text(encoding="utf-8"))["rows"]


def _archive_raw_results(root: Path) -> tuple[list[str], list[str]]:
    """(differences, identical_after_decompression): each Archive receipt's raw-copy result after
    every later note. Differences are real mismatches, or mismatches not yet resolved."""
    diff, same = [], []
    a = Archive(root)
    for day, rel in day_manifests(a):
        m = a.load_json(rel)
        seen = set()
        for rid, name, ts, rc, where, ntype in _checks(m):
            if (rid, name, ts) in seen:
                continue
            seen.add((rid, name, ts))
            result, method = final_raw_result(m, rid, name, ts)
            if result == "match_after_decoding":
                same.append(f"{day} {name} ({method})")
            elif result == "mismatch":
                d = rc.get("diagnostic") or {}
                summ = d.get("difference_summary")
                diff.append(f"{day} {name}" + (f" ({summ})" if summ else " (not yet diagnosed)"))
    return diff, same


def ghsa_line(summary: dict) -> str:
    g = summary.get("ghsa_ids") or {}
    glob, repo = g.get("global_database", {}), g.get("repository_advisory", {})
    return (f"- GHSA IDs on revealed findings: {g.get('total', 0)}. In GitHub's global advisory database: "
            f"{glob.get('exists', 0)}. With no entry there (confirmed without the token): "
            f"{glob.get('not_in_global_database', 0)}; of these, found as the repository's own advisory: "
            f"{repo.get('exists', 0)}, not found there: {repo.get('not_found', 0)}, no repository known: "
            f"{repo.get('no_repository_known', 0)}, not readable: {repo.get('lookup_unreadable', 0)}.")


def weekly_report(root: Path, run_date: str, sample: bool = False) -> str:
    root = Path(root)
    snaps, gaps = _rows(root, "snapshots"), _rows(root, "gaps")
    ver = _rows(root, "verification")
    summary = _rows(root, "summary")[0]
    mism, same = _archive_raw_results(root)
    ours = [s for s in snaps if s["source_kind"] == "our_capture"]
    latest = ours[-1]
    g = [x for x in gaps if x["source_kind"] == "our_capture"][-1]
    hc = Counter(r["hash_check"] for r in ver)
    title = "Sample lookups (5 findings)" if sample else "Weekly review report"
    L = [f"# {title}, {run_date}", "",
         "Generated by deterministic code from the files in `data/`. No language model wrote any part of this "
         "report. Quotations of the program's own words are marked with a bar and attributed.", "",
         "## Summary", "",
         f"- Latest snapshot in our captures: revision {latest['revision']}, as of {latest['as_of_utc']}, "
         f"first captured by us {latest['first_seen_by_us']}.",
         f"- Revealed findings checked against their finding cards (rule R2): {len(ver)}. "
         f"Hash matches: {hc.get('match', 0)}. Hash mismatches: {hc.get('mismatch', 0)}. "
         f"Preimage withheld by the program: {hc.get('preimage_withheld', 0)}. "
         f"Card or preimage could not be fetched or read: {hc.get('unavailable', 0)}. "
         f"Not checked yet: {hc.get('not_checked', 0)}.",
         f"- Public-record lookups (rules R3 and R4), per finding: "
         + ", ".join(f"{k} {v}" for k, v in summary["lookups"].items()) + ".",
         f"- Identifiers found in public records: " + ", ".join(f"{k} {v}" for k, v in summary["ids_exist"].items()) + ".",
         ghsa_line(summary),
         f"- Fix merged into the default branch: " + ", ".join(f"{k} {v}" for k, v in summary["fix_merged"].items()) + ".",
         f"- Internet Archive copies identical to ours after decompression: {len(same)}"
         + (f" ({'; '.join(same[:10])}{'; ...' if len(same) > 10 else ''})" if same else "") + ".",
         f"- Fully checked: {summary['checked_n']} of {summary['checked_of']}. A finding is fully checked when "
         "its hash check is conclusive (match, mismatch or preimage withheld), its identifiers are confirmed in "
         "public records or it has none, and whether its fix was merged has been determined.", ""]
    ic = summary["interval_comparisons"]
    L += ["Intervals from the cards' dates (rule R5; descriptive only):", ""]
    names = {"days_report_to_patch": "report to patch", "days_patch_to_reveal": "patch to reveal",
             "days_report_to_reveal": "report to reveal"}
    for k, label in names.items():
        c = ic[k]
        L.append(f"- {label}: {c['with_dates']} findings with both dates; {c['within']} within "
                 f"{c['reference_days']} days, {c['above']} above {c['reference_days']} days.")
    L += [f"- report to fix merge: {ic['days_report_to_merge']['with_dates']} findings with both dates.",
          f"- Reference days come from {summary['policy_source'] or 'the policy page (no dated copy yet)'} "
          "and, for 135 days, from the program's April post.", ""]

    items = []
    if summary["program_revealed_count"] != summary["revealed"]:
        items.append(f"The dashboard's data file states {summary['program_revealed_count']} revealed findings. "
                     f"The dashboard's ledger lists {summary['revealed']} entries in the revealed tier. Both "
                     f"figures are recorded as found (revision {latest['revision']}).")
    for label, claimed, itemized, what in (
            ("patched", g["patched_claimed"], g["patched_itemized"], "ledger entries flagged fixed in response"),
            ("CVE records", g["cves_claimed"], g["cves_itemized"], "unique CVE IDs on ledger entries"),
            ("GitHub Security Advisories", g["ghsas_claimed"], g["ghsas_itemized"], "unique GHSA IDs on ledger entries"),
            ("reported to maintainers", g["reported_claimed"], g["reported_flagged_in_ledger"],
             "ledger entries flagged disclosed")):
        if claimed != itemized:
            items.append(f"The dashboard states {claimed} {label}. Its published ledger itemizes {itemized} "
                         f"({what}), revision {g['revision']}.")
    for r in ver:
        fid = r["finding_id"]
        if r["ids_exist"] == "not_found":
            missing = [i for i, d in r["ids_exist_detail"].items() if "exists" not in d.values()]
            items.append(f"The dashboard lists {', '.join(missing)} for {fid}. Public records show no record for "
                         f"{'it' if len(missing) == 1 else 'them'} in the GitHub Advisory Database or NVD.")
        if r["fix_merged"] == "no":
            items.append(f"The dashboard lists a fix for {fid} ({r['fix_url']}). Public records show it is not "
                         f"merged into the project's default branch. {r['notes'] or ''}".strip())
        for note in (r["notes"] or "").split(". "):
            if note.startswith("The ledger names project"):
                items.append(f"{fid}: {note.rstrip('.')}.")
        if r["lookup_status"] in ("lookup_unreadable", "rate_limited", "network_error", "github_refused_token"):
            items.append(f"Lookups for {fid} are incomplete ({r['lookup_status']}): {r['notes'] or 'see records/'}.")
    if mism:
        items.append(f"The Internet Archive's raw copy differed from ours {len(mism)} time(s), with the byte "
                     "comparison unresolved or showing a real content difference: "
                     + "; ".join(mism[:10]) + ("; ..." if len(mism) > 10 else "")
                     + ". The diagnostic for each is in that day's MANIFEST.json.")
    L += [REPORT_HEADING, "", f"{len(items)} item(s). Each needs a person to read the evidence before anything "
          "is said about it.", ""]
    L += [f"{n}. {t}" for n, t in enumerate(items, 1)]

    withheld = [r for r in ver if r["hash_check"] == "preimage_withheld"]
    if withheld:
        L += ["", "## Preimages withheld by the program", "",
              "These are not mismatches and not errors. Each card says the preimage is withheld; its words:", ""]
        for r in withheld:
            L += [f"- {r['finding_id']}, quoted from the program's finding card:", "",
                  f"> {r['withheld_statement']}", ""]
    L += ["", "## Evidence", "",
          "- Published tables: `data/` (column meanings in `data/schema/`).",
          "- Finding cards and per-card checks: `cards/<finding ID>/`.",
          "- Public-record responses as received: `records/` (sources and terms in `records/README.md`).",
          "- Raw captures and Internet Archive receipts: `captures/`.", ""]
    text = "\n".join(L)
    check_text(text, "weekly report")
    return text


def top_section(report: str, path: str) -> str:
    """The part of the report used as the pull request description."""
    head, sep, rest = report.partition(REPORT_HEADING)
    count = rest.strip().splitlines()[0] if sep else ""
    return head + (f"{REPORT_HEADING}\n\n{count} The full list is in `{path}`.\n" if sep else "")
